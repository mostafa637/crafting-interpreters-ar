"""The build script: weaves ``book/`` + ``java/`` + ``c/`` into Typst sources.

Usage::

    python3 -m typstbuild                       # generate every .typ file
    python3 -m typstbuild --lang ar             # only the Arabic sources
    python3 -m typstbuild --pdf                 # ... and typeset the PDFs
    python3 -m typstbuild --only scanning       # just one chapter

The generated files live in ``typst/``: one Typst file per chapter
(``typst/chapters/*.typ``) plus the document roots ``main.typ`` and
``main-ar.typ``.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
import textwrap
from pathlib import Path
from typing import Optional

from . import mdparse as md
from .emit import TypstEmitter
from .i18n import label_for, title_for
from .model import Book, Page
from .text import to_file_name, typst_string, word_count

FRONT_MATTER_TITLES = {"Crafting Interpreters", "Table of Contents"}


class BookIndex:
    """The set of labels that exist in the generated Typst sources.

    Links in the prose point at ``scanning.html`` or
    ``representing-code.html#metaprogramming-the-trees``; mapping those to
    Typst labels gives the PDF working internal cross references.
    """

    def __init__(self, book: Book):
        self.labels: set[str] = set()
        for page in book.pages:
            self.labels.add(f"chap-{page.file_name}")
            for header in page.headers.values():
                if header.level == 2 and not header.is_special:
                    self.labels.add(f"chap-{page.file_name}-{header.anchor}")
                elif header.is_special:
                    self.labels.add(f"chap-{page.file_name}-{header.anchor}")

    def label_for_href(self, href: str) -> Optional[str]:
        if not href.endswith(".html") and ".html#" not in href:
            return None
        if "#" in href:
            file_part, fragment = href.split("#", 1)
        else:
            file_part, fragment = href, ""
        name = file_part[:-len(".html")]
        label = f"chap-{name}"
        if fragment:
            label += f"-{fragment}"
        return label if label in self.labels else None


