# Driver
# ---------------------------------------------------------------------------


def build_language(book: Book, index: BookIndex, lang: str, out_dir: Path, only: Optional[str]):
    includes: list[str] = []
    stats = {"words": 0, "code": 0}

    for page in book.pages:
        if only and only not in page.file_name:
            continue

        if page.title == "Crafting Interpreters":
            includes.append(emit_title_page(lang, out_dir))
            continue

        if page.title == "Table of Contents":
            includes.append(emit_contents(book, lang, out_dir))
            continue

        translate_page(book, page, lang, Path(book.root))

        if page.title == "Dedication":
            includes.append(emit_dedication(book, page, lang, out_dir))
            stats["words"] += sum(word_count(line) for line in page.lines)
            continue

        includes.append(emit_page(book, page, index, lang, out_dir))
        stats["words"] += sum(word_count(line) for line in page.lines)

    return includes, stats


def compile_pdf(root: Path, out_dir: Path, main: Path, pdf_path: Path) -> None:
    import typst

    typst.compile(
        str(main),
        output=str(pdf_path),
        root=str(root),
        font_paths=[str(out_dir / "fonts")],
        ignore_system_fonts=True,
    )


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="typstbuild", description=__doc__)
    parser.add_argument("--root", default=".", help="repository root")
    parser.add_argument("--out", default="typst", help="output directory for .typ files")
    parser.add_argument(
        "--lang", default="both", choices=["en", "ar", "both"], help="which edition to build"
    )
    parser.add_argument("--only", default=None, help="only build pages matching this substring")
    parser.add_argument("--pdf", action="store_true", help="also typeset the PDFs")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    out_dir = (root / args.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    print(f"Reading sources from {root} ...")
    book = Book(str(root))
    index = BookIndex(book)

    languages = ["en", "ar"] if args.lang == "both" else [args.lang]
    for lang in languages:
        if lang != "en":
            # Point the pages at their translated Markdown *before* indexing,
            # so the cross references of this edition use the anchors the
            # translated headings produce.
            for page in book.pages:
                translate_page(book, page, lang, root)
            index = BookIndex(book)
        includes, stats = build_language(book, index, lang, out_dir, args.only)  # type: ignore[arg-type]
        main_path = emit_main(book, includes, lang, out_dir)
        print(
            f"[{lang}] wrote {len(includes)} files, "
            f"{stats['words']:,} words of prose -> {main_path.relative_to(root)}"
        )

        if args.pdf and not args.only:
            pdf_path = out_dir / ("crafting-interpreters.pdf" if lang == "en" else "crafting-interpreters-ar.pdf")
            try:
                compile_pdf(root, out_dir, main_path, pdf_path)
            except Exception as error:  # pragma: no cover - reported to the user
                print(f"[{lang}] PDF failed: {error}", file=sys.stderr)
                return 1
            print(f"[{lang}] typeset {pdf_path.relative_to(root)}")

    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
