# Chapter emission
# ---------------------------------------------------------------------------


def translate_page(book: Book, page: Page, lang: str, root: Path) -> Page:
    """Points *page* at the translated Markdown file, when there is one."""
    if lang == "en":
        return page
    translated = root / "book" / "ar" / f"{page.file_name}.md"
    if translated.exists():
        page.set_markdown_path(str(translated))
    return page


def emit_page(book: Book, page: Page, index: BookIndex, lang: str, out_dir: Path) -> str:
    """Generates the Typst file for one page and returns its file name."""
    parser = md.MarkdownParser(book, page)
    blocks = parser.parse(_clean_lines(page.lines))

    emitter = TypstEmitter(book, page, lang=lang)
    emitter.index = index  # type: ignore[attr-defined]
    source = emitter.render(blocks)

    chapter_dir = "chapters-ar" if lang == "ar" else "chapters"
    path = out_dir / chapter_dir / f"{page.file_name}.typ"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")

    for warning in emitter.warnings:
        print(f"  warning: {warning}", file=sys.stderr)

    return f"{chapter_dir}/{page.file_name}.typ"


def _clean_lines(lines: list[str]) -> list[str]:
    """Resolves the book's reference-style links before parsing.

    The Markdown uses ``[text][label]`` plus a list of ``[label]: url``
    definitions at the bottom of each chapter.
    """
    definitions: dict[str, str] = {}
    kept: list[str] = []

    for line in lines:
        match = re.match(r"^\[([^\]]+)\]:\s*(\S+)\s*$", line)
        if match is not None:
            definitions[match.group(1).lower()] = match.group(2)
            continue
        kept.append(line)

    if not definitions:
        return lines

    text = "\n".join(kept)

    def replace(match: re.Match) -> str:
        label = (match.group(2) or match.group(1)).lower()
        url = definitions.get(label)
        if url is None:
            return match.group(0)
        return f"[{match.group(1)}]({url})"

    text = re.sub(r"\[([^\]]+)\]\[([^\]]*)\]", replace, text)
    return text.split("\n")


