def emit_title_page(lang: str, out_dir: Path) -> str:
    path = out_dir / "frontmatter" / "title.typ"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// Generated by tools/typstbuild.\n"
        '#import "../template/book.typ": *\n\n'
        "#title-page() <chap-index>\n",
        encoding="utf-8",
    )
    return "frontmatter/title.typ"


def emit_dedication(book: Book, page: Page, lang: str, out_dir: Path) -> str:
    """The dedication page is a centered image plus a line of text."""
    image_src = "none"
    text_value = "none"

    for block in md.MarkdownParser(book, page).parse(_clean_lines(page.lines)):
        if isinstance(block, md.ImageBlock):
            image_src = f'"{"/site/" + block.src.lstrip("/")}"'
        elif isinstance(block, md.Paragraph):
            emitter = TypstEmitter(book, page, lang=lang)
            value = emitter.emit_inline_nodes(block.inlines)
            if value.strip():
                text_value = f"[{value}]"

    path = out_dir / "frontmatter" / "dedication.typ"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// Generated by tools/typstbuild.\n"
        '#import "../template/book.typ": *\n\n'
        f"#dedication-page(image-src: {image_src}, line: {text_value}) <chap-dedication>\n",
        encoding="utf-8",
    )
    return "frontmatter/dedication.typ"


def emit_contents(book: Book, lang: str, out_dir: Path) -> str:
    """The table of contents, with live page references."""
    lines = [
        "// Generated by tools/typstbuild.",
        '#import "../template/book.typ": *',
        "",
        "#table-of-contents[",
    ]

    for page in book.pages:
        if page.is_part:
            lines.append(
                f'  #toc-entry(number: "{page.number_string}.", '
                f'title: {typst_string(title_for(page.title, lang))}, '
                f"label: <chap-{page.file_name}>)"
            )
            continue

        if page.title in FRONT_MATTER_TITLES:
            if page.title == "Table of Contents":
                continue
            lines.append(
                f"  #toc-entry(title: {typst_string(title_for(page.title, lang))}, "
                f"label: <chap-{page.file_name}>)"
            )
            continue

        number = f"{page.number_string}." if page.number_string else none_string()
        lines.append(
            f'  #toc-entry(number: "{number}", title: "{page.title}", '
            f"label: <chap-{page.file_name}>)"
        )

        for header in page.headers.values():
            if not header.is_special:
                continue
            anchor = header.anchor
            title = (
                label_for("challenges", lang)
                if header.is_challenges
                else header.name.replace("Design Note: ", "")
            )
            lines.append(
                f"  #toc-entry(level: 1, title: {typst_string(title)}, "
                f"label: <chap-{page.file_name}-{anchor}>, note: true)"
            )

    lines.append("] <chap-contents>")
    lines.append("")

    path = out_dir / "frontmatter" / "contents.typ"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return "frontmatter/contents.typ"


def none_string() -> str:
    return ""


# ---------------------------------------------------------------------------
# Document root
# ---------------------------------------------------------------------------


def emit_main(book: Book, includes: list[str], lang: str, out_dir: Path) -> Path:
    name = "main.typ" if lang == "en" else "main-ar.typ"
    path = out_dir / name
    lines = [
        "// Generated by tools/typstbuild -- the document root.",
        f'#import "template/book.typ": *',
        f'#show: book.with(lang: "{lang}")',
        "",
    ]
    for include in includes:
        lines.append(f'#include "{include}"')
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


